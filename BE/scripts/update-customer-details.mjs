async function main() {
  const regions = await prisma.region.findMany();
  const regionMap = {};
  for (const r of regions) {
    regionMap[r.name.toLowerCase().replace(/[^a-z0-9]/g, '')] = r;
  }

  for (const data of customerDetails) {
    const existing = await prisma.customer.findFirst({
      where: { name: data.name },
    });
    if (!existing) {
      console.log(`SKIP: not found - ${data.name}`);
      continue;
    }

    const regionKey = data.province.toLowerCase().replace(/[^a-z0-9]/g, '');
    const region = regionMap[regionKey] || regions[0];

    const updateData = {
      shortName: data.shortName,
      hospitalName: data.hospitalName,
      customerType: data.customerType,
      taxCode: data.taxCode || null,
      email: data.email || null,
      website: data.website || null,
      phone: data.phone || null,
      contactPerson: data.contactPerson || null,
      contactPosition: data.contactPosition || null,
      contactPhone: data.contactPhone || null,
      contactEmail: data.contactEmail || null,
      province: data.province || null,
      district: data.district || null,
      ward: data.ward || null,
      address: data.address || null,
      fullAddress: data.fullAddress || null,
      note: data.note || null,
      regionId: region.id,
    };

    await prisma.customer.update({
      where: { id: existing.id },
      data: updateData,
    });
    console.log(`UPDATED: ${data.name}`);
  }

  console.log('\nDone! Đã cập nhật thông tin chi tiết cho khách hàng.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
