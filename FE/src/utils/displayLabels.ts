export function displayLabel(value: unknown) {
  const rawValue = String(value ?? '');
  return displayLabels[rawValue.toUpperCase()] || rawValue.replaceAll('_', ' ');
}

export function enumOptions(values: string[], labels: Record<string, string> = {}): SelectOption[] {
  return values.map((value) => ({ label: labels[value] || displayLabel(value), value }));
}
